// БЛОК 3.5 — вечный замок словаря (audit-v2/GOTHIC-LEXICON.md).
//
// Партии A-H перевели весь видимый текст на плотную готику. Ратчет держит его
// там: любая новая строка со старым канцелярским словом («задача», «архив»,
// «дедлайн», «приоритет», «шаблон», «группа», «цвет», «заметка», «импорт/
// экспорт», «конфликт») роняет тест, пока её не переведут ИЛИ не внесут в
// ALLOW с обоснованием.
//
// Что проверяем и чего НЕ проверяем:
// · комментарии кода не трогаем вовсе — они по-русски и говорят на языке
//   реализации («задача», «дедлайн»); срезаем их перед сканом;
// · зона-исключение §4 карты (спасательный контур, журнал синка, редакторская
//   панель Гримуара, даты/единицы, названия цветов) живёт в ALLOW;
import { it, expect } from 'vitest';
import { readFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// Комментарии срезаем ДО скана: `//` только в начале строки или после символа,
// после которого он не может быть частью URL или литерала пути.
const strip = (s) => s
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/^\s*\/\/.*$/gm, '')
    .replace(/([^:'"`])\/\/[^'"`\n]*$/gm, '$1');

// Старый голос. Ключ — понятие, значение — что должно стоять вместо него.
const FORBIDDEN = [
    [/задач\w*|Задач\w*/,           'обет / обеты'],
    [/[Аа]рхив\w*/,                 'склеп · предать склепу · воскресить'],
    [/дедлайн\w*|Дедлайн\w*/,       'исход'],
    [/[Пп]риоритет\w*/,             'ранг'],
    [/[Шш]аблон\w*/,                'образец'],
    [/[Гг]рупп\w*/,                 'свод'],
    [/[Цц]вет\w*/,                  'витраж (названия самих цветов — в ALLOW, §4)'],
    [/[Зз]аметк\w*/,                'примечание (у обета) · запись (в Гримуаре)'],
    [/[Ии]мпорт\w*|[Ээ]кспорт\w*/,  'прочесть свиток / запечатать свиток'],
    [/[Сс]нимк\w*/,                 'слепок (летопись) — автоснимки отката в ALLOW, §4'],
    [/[Кк]онфликт\w*/,              'разночтение (журнал синка — в ALLOW, §4)'],
    [/[Пп]одпункт\w*/,              'звено / звенья'],
    [/[Аа]ктивны\w*|[Вв]ыполненн\w*/, 'неисполненные / исполненные'],
    [/[Уу]далить навсегда/,         'уничтожить'],
    [/[Пп]оиск\w*|[Ии]скать/,       'зов · взывать · оборвать зов'],
    [/[Рр]езервн\w*/,               'полный свиток'],
    [/[Зз]акреп\w*|[Оо]ткреп\w*/,   'приковать · расковать · Прикованные'],
    [/(?<![А-Яа-яЁё])[Вв]ернуть/,   'воскресить (в склепе и Гримуаре)'],
    [/[Фф]окус\w*/,                 'замкнуться · разомкнуться · Замкнуто'],
    [/[Уу]ведомлен\w*/,             'вести'],
    [/[Пп]ереименов\w*/,            'наречь'],
    [/[Оо]чистить|[Оо]чистка/,      'снять · оборвать зов · опустошить'],
    [/подп\./,                      'звен.'],
];

// Разрешённые вхождения: точная подстрока строки-исключения → почему.
const ALLOW = [
    ['Автоснимки сохраняются',          '§4 спасательный контур: точки восстановления'],
    ["'pull: v'",                       '§4 журнал синка (диагностика)'],
    ['конфликт версий — повтор',        '§4 журнал синка (диагностика)'],
];

// Строки, разрешённые ЦЕЛИКОМ (сравнение по обрезанной строке, а не по вхождению
const ALLOW_EXACT = [
];

const files = ['index.html', ...readdirSync(join(root, 'dusk')).filter(f => f.endsWith('.ts')).map(f => 'dusk/' + f)];

it('старый канцелярский голос не вернулся в видимый текст', () => {
    const leaks = [];
    for (const f of files) {
        const src = strip(readFileSync(join(root, f), 'utf8'));
        src.split(/\r?\n/).forEach((line, i) => {
            if (ALLOW.some(([frag]) => line.includes(frag))) return;
            if (ALLOW_EXACT.some(([exact]) => line.trim() === exact)) return;
            for (const [re, hint] of FORBIDDEN) {
                const m = line.match(re);
                if (m) { leaks.push(`${f}:${i + 1} «${m[0]}» → ${hint}\n      ${line.trim().slice(0, 120)}`); break; }
            }
        });
    }
    expect(leaks, `старый голос вернулся:\n  ${leaks.join('\n  ')}`).toEqual([]);
});

// Замок на сам ALLOW: список исключений должен оставаться коротким и осмысленным.
// Если он пухнет — значит перевод откатывают через «исключения», а не через слова.
it('список исключений не разрастается', () => {
    expect(ALLOW.length).toBeLessThanOrEqual(10);
});

// Ключевые слова словаря должны реально присутствовать — иначе «зелёный» ратчет
// можно получить, просто вычистив весь текст.
it('новый словарь на месте', () => {
    const all = files.map(f => readFileSync(join(root, f), 'utf8')).join('\n');
    for (const w of ['обет', 'склеп', 'исход', 'ранг', 'образец', 'свод', 'витраж',
                     'примечание', 'свиток', 'разночтен', 'круговорот', 'звен',
                     'приков', 'воскреси', 'замкну', 'наречь', 'вести']) {
        expect(all.toLowerCase().includes(w), `слово «${w}» пропало из интерфейса`).toBe(true);
    }
});
